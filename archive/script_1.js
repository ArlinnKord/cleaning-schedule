// Алгоритм распределения: этажи целиком, балансировка по минутам
// 1. Сортируем этажи по размеру (самые большие — первыми)
// 2. Каждый этаж отдаём горничной, у которой будет ближе всего к средней нагрузке
// 3. Ограничение: не больше 2 выезд/заезд на горничную

const горничные = Array.from({ length: КОЛ_ГОРНИЧНЫХ }, () => []);
const минГорничных = Array(КОЛ_ГОРНИЧНЫХ).fill(0);
const счетчикВыездЗаезд = Array(КОЛ_ГОРНИЧНЫХ).fill(0);

// Группируем по этажам в порядке маршрута
const этажи = [];
let текущийЭтаж = null;
let текущиеЗадачи = [];

tasks.forEach(t => {
  const ключ = `${t.корпус}${t.этаж}`;
  if (ключ !== текущийЭтаж) {
    if (текущиеЗадачи.length > 0) {
      этажи.push({ ключ: текущийЭтаж, задачи: текущиеЗадачи });
    }
    текущийЭтаж = ключ;
    текущиеЗадачи = [];
  }
  текущиеЗадачи.push(t);
});
if (текущиеЗадачи.length > 0) этажи.push({ ключ: текущийЭтаж, задачи: текущиеЗадачи });

const общаяНагрузка = tasks.reduce((s, t) => s + t.мин, 0);

// Сортируем этажи по убыванию минут (самые большие — первыми)
этажи.sort((a, b) => {
  const мA = a.задачи.reduce((s, t) => s + t.мин, 0);
  const мB = b.задачи.reduce((s, t) => s + t.мин, 0);
  return мB - мA;
});

console.log(`\n📊 Этажей: ${этажи.length}, горничных: ${КОЛ_ГОРНИЧНЫХ}, всего: ${общаяНагрузка} мин`);

этажи.forEach((этаж) => {
  const минЭтажа = этаж.задачи.reduce((s, t) => s + t.мин, 0);
  const выездЗаездНаЭтаже = этаж.задачи.filter(t => t.тип === "40 выезд/заезд").length;

  // Какая горничная будет иметь нагрузку ближе всего к средней, если возьмёт этот этаж?
  const средняя = (общаяНагрузка + минЭтажа) / (КОЛ_ГОРНИЧНЫХ + 1); // примерная цель

  let лучшая = -1;
  let лучшийБалл = Infinity;

  for (let i = 0; i < КОЛ_ГОРНИЧНЫХ; i++) {
    // Проверяем ограничение по выезд/заезд
    if (счетчикВыездЗаезд[i] + выездЗаездНаЭтаже > 2) continue;

    const новаяНагрузка = минГорничных[i] + минЭтажа;
    const балл = Math.abs(новаяНагрузка - средняя);

    // Штраф за смену корпуса (чтобы держались в одном здании)
    const естьЗадачиСДругогоКорпуса = горничные[i].length > 0 &&
      горничные[i].some(t => t.корпус !== этаж.задачи[0].корпус);
    if (естьЗадачиСДругогоКорпуса) continue; // не мешаем корпуса

    if (балл < лучшийБалл) {
      лучшийБалл = балл;
      лучшая = i;
    }
  }

  // Если всех забраковали по корпусам — выбираем самую свободную
  if (лучшая === -1) {
    лучшая = минГорничных.indexOf(Math.min(...минГорничных));
  }

  этаж.задачи.forEach(t => {
    t.горничная = лучшая;
    t.цвет = ЦВЕТА[лучшая].ARGB;
    горничные[лучшая].push(t);
    минГорничных[лучшая] += t.мин;
    if (t.тип === "40 выезд/заезд") счетчикВыездЗаезд[лучшая]++;
  });
});

// Сортируем внутри каждой группы по маршруту
горничные.forEach(g => {
  g.sort((a, b) => {
    if (a.корпус !== b.корпус) return a.корпус.localeCompare(b.корпус);
    if (a.этаж !== b.этаж) return a.этаж - b.этаж;
    return a.номер - b.номер;
  });
});

