      c40vz: t.тип === "40 выезд/заезд" ? t.мин : "",
      c40v: t.тип === "40 выезд" ? t.мин : "",
      c20: t.тип === "20" ? t.мин : "",
      колво: t.человек || "",
      горничная: ЦВЕТА[t.горничная].имя,
      коммент: t.коммент,
