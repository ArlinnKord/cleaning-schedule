// 3. РАСПРЕДЕЛЕНИЕ ПО ГОРНИЧНЫМ
// ============================================================
const КОЛ_ГОРНИЧНЫХ = tasks.length >= 10 ? 4 : 3;
const ЦВЕТА = [
  { имя: "Красный",  ARGB: "FFE74C3C" },
  { имя: "Синий",    ARGB: "FF3498DB" },
  { имя: "Зелёный",  ARGB: "FF2ECC71" },
  { имя: "Жёлтый",   ARGB: "FFF1C40F" },
];

// Сортируем по (корпус, этаж, номер) — маршрут уборки
tasks.sort((a, b) => {
  if (a.корпус !== b.корпус) return a.корпус.localeCompare(b.корпус);
  if (a.этаж !== b.этаж) return a.этаж - b.этаж;
  return a.номер - b.номер;
});

